"""
The ACS, sepsis and DKA checks used to be hand-written in
smart_diagnostic_engine.py; they now live in the `criteria` sections of
CARD-ACUTE-CORONARY-SYNDROME, ID-SEPSIS and ENDO-DKA.

fixtures/smart_engine_golden.json was generated by the hand-written
evaluators (commit 286ffe7) on the synthetic patients in
smart_engine_cases.py. These tests require the criteria engine to reproduce
every criterion, value, expected range, detail, probability, severity,
severity reason, missing test and evaluation status exactly. Only the result
ids (now tree ids) and the recommendation wording changed by design.

Equivalence for all three was proven in commit 83c4054 (Phase 1). Sepsis and
DKA criteria were then deliberately updated (SSC 2021: qSOFA not used alone;
2024 hyperglycemic-crises consensus), so only ACS is still compared here; the
golden file is kept unchanged as the record of the previous behavior.
"""

import json
from datetime import datetime

import pytest

from backend.services.smart_diagnostic_engine import SmartDiagnosticEngine
from backend.tests.smart_engine_cases import CASES, GOLDEN_PATH, LEGACY_TO_TREE, patient, serialize

GOLDEN = json.loads(GOLDEN_PATH.read_text())
NOW = datetime(2026, 10, 19, 8, 0)


@pytest.fixture(scope="module")
def engine():
    return SmartDiagnosticEngine()


def test_golden_covers_every_case():
    assert set(GOLDEN) == set(CASES)


# Evaluators whose criteria are unchanged since Phase 1 (83c4054)
UNCHANGED = ["CARD-ACS"]


@pytest.mark.parametrize("case", sorted(CASES))
@pytest.mark.parametrize("legacy_id", UNCHANGED)
def test_each_evaluator_matches_previous_output(engine, case, legacy_id):
    result = engine.evaluate_tree(LEGACY_TO_TREE[legacy_id], patient(case), now=NOW)
    assert serialize(result) == GOLDEN[case]["raw"][legacy_id]


def _still_shown(golden_entry):
    """Acute cards are now shown only when a criterion is met or a result could
    not be read (an unusable result carries a value); a card that only said
    "not measured" is no longer shown."""
    return bool(golden_entry["criteria_met"]) or any(c["value"] for c in golden_entry["criteria_unknown"])


@pytest.mark.parametrize("case", sorted(CASES))
def test_shown_results_match_previous_output(engine, case):
    """Same content for every card still shown (after insufficient-data labelling)."""
    unchanged_trees = {LEGACY_TO_TREE[k] for k in UNCHANGED}
    shown = {e.diagnosis_id: serialize(e) for e in engine.evaluate_patient(patient(case), now=NOW)
             if e.diagnosis_id in unchanged_trees}
    expected = {LEGACY_TO_TREE[k]: v for k, v in GOLDEN[case]["shown"].items()
                if k in UNCHANGED and _still_shown(v)}
    assert shown == expected


def test_no_other_tree_appears_for_acute_only_cases(engine):
    """The chronic-condition trees stay hidden when their tests were not done."""
    ids = {e.diagnosis_id for e in engine.evaluate_patient(patient("all_abnormal"), now=NOW)}
    assert ids == set(LEGACY_TO_TREE.values())
