"""
ICPC-2 codes for decision trees: loading, status and validation.

Codes come from a tree's own codes.icpc2 list and from
backend/data/icpc2_mapping.yml (the place for a licensed mapping, with
provenance). No codes are generated by RealDiag. A tree with none reports
PENDING_STATUS, which every response that shows ICPC-2 carries.
"""
import re
from functools import lru_cache
from pathlib import Path
from typing import Any, Dict, List, Optional

import yaml

from .tree_schema import icpc2_codes as tree_icpc2_codes

MAPPING_PATH = Path(__file__).resolve().parents[1] / "data" / "icpc2_mapping.yml"
PENDING_STATUS = "pending licensed mapping and review"
REVIEWED_STATUS = "reviewed"
CODE_PATTERN = re.compile(r"^[A-Z][0-9]{2}(\.[0-9]+)?$")
REQUIRED_FIELDS = ("code", "label", "mapped_by", "reviewed_by", "reviewed_on")


@lru_cache(maxsize=1)
def load_mapping(path: str = str(MAPPING_PATH)) -> Dict[str, Any]:
    data = yaml.safe_load(Path(path).read_text(encoding="utf-8")) or {}
    data.setdefault("status", PENDING_STATUS)
    data["mappings"] = data.get("mappings") or {}
    return data


def icpc2_for(tree: Dict[str, Any], tree_id: Optional[str] = None) -> Dict[str, Any]:
    """{"icpc2": [codes], "icpc2_status": ...} for a tree."""
    mapping = load_mapping()
    tid = tree_id or tree.get("tree_id") or tree.get("id")
    codes = list(tree_icpc2_codes(tree))
    for entry in mapping["mappings"].get(tid) or []:
        if isinstance(entry, dict) and entry.get("code") and entry["code"] not in codes:
            codes.append(str(entry["code"]))
    status = REVIEWED_STATUS if codes and mapping.get("status") == REVIEWED_STATUS else PENDING_STATUS
    return {"icpc2": codes if status == REVIEWED_STATUS else [], "icpc2_status": status}


def mapping_problems(mapping: Dict[str, Any], tree_ids: List[str], tree_codes: Dict[str, List[str]]) -> List[str]:
    """Problems in the mapping file and in trees' own codes.icpc2 (empty = valid)."""
    problems = []
    status = mapping.get("status")
    if status not in (PENDING_STATUS, REVIEWED_STATUS):
        problems.append(f"status must be '{PENDING_STATUS}' or '{REVIEWED_STATUS}'")
    if status == REVIEWED_STATUS and not (mapping.get("source") and mapping.get("version")):
        problems.append("a reviewed mapping must name its licensed source and version")
    entries = mapping.get("mappings") or {}
    if not isinstance(entries, dict):
        return problems + ["mappings must be a mapping of tree id -> list of codes"]
    if entries and status != REVIEWED_STATUS:
        problems.append(f"codes cannot be added while status is '{status}'")
    known = set(tree_ids)
    for tid, items in entries.items():
        if tid not in known:
            problems.append(f"{tid}: unknown tree")
        for i, item in enumerate(items if isinstance(items, list) else [items]):
            if not isinstance(item, dict):
                problems.append(f"{tid}[{i}]: must be a mapping with {', '.join(REQUIRED_FIELDS)}")
                continue
            missing = [f for f in REQUIRED_FIELDS if not item.get(f)]
            if missing:
                problems.append(f"{tid}[{i}]: missing {', '.join(missing)}")
            if item.get("code") and not CODE_PATTERN.match(str(item["code"])):
                problems.append(f"{tid}[{i}]: '{item['code']}' is not an ICPC-2 code (letter + two digits)")
    for tid, codes in tree_codes.items():
        for code in codes:
            if not CODE_PATTERN.match(code):
                problems.append(f"{tid}: codes.icpc2 '{code}' is not an ICPC-2 code (letter + two digits)")
            elif status != REVIEWED_STATUS:
                problems.append(f"{tid}: codes.icpc2 has codes while the ICPC-2 mapping is '{status}'")
    return problems
